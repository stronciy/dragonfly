-- Категорія «Внесення ЗЗР, добрив» перейменовується на «Внесення ЗЗР, мікродобрив».
-- id категорії не змінюється, тож прив'язки підкатегорій і заказів лишаються чинними.
UPDATE service_categories
SET name = 'Внесення ЗЗР, мікродобрив',
    name_ua = CASE WHEN name_ua = 'Внесення ЗЗР, добрив' THEN 'Внесення ЗЗР, мікродобрив' ELSE name_ua END,
    updated_at = NOW()
WHERE id = '3' AND name = 'Внесення ЗЗР, добрив';
